function getTightAlphaBounds(
  ctx: CanvasRenderingContext2D,
  margin = 12
): { x: number; y: number; width: number; height: number } {
  const w = ctx.canvas.width;
  const h = ctx.canvas.height;
  const imgData = ctx.getImageData(0, 0, w, h);
  const data = imgData.data;
  let minX = w, minY = h, maxX = -1, maxY = -1;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const alpha = data[(y * w + x) * 4 + 3];
      if (alpha > 5) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }

  if (maxX === -1) {
    return { x: 0, y: 0, width: w, height: h };
  }

  const tightX = Math.max(0, minX - margin);
  const tightY = Math.max(0, minY - margin);
  const tightW = Math.min(w - tightX, maxX - minX + 1 + margin * 2);
  const tightH = Math.min(h - tightY, maxY - minY + 1 + margin * 2);

  return {
    x: tightX,
    y: tightY,
    width: Math.max(16, tightW),
    height: Math.max(16, tightH),
  };
}

function applyProcessedMask(
  targetCtx: CanvasRenderingContext2D,
  mask: LayerMask,
  width: number,
  height: number
) {
  const density = Math.max(0, Math.min(100, mask.density !== undefined ? mask.density : 100)) / 100;
  const feather = Math.max(0, mask.feather || 0);

  const mBuf = document.createElement('canvas');
  mBuf.width = width;
  mBuf.height = height;
  const mbCtx = mBuf.getContext('2d', { willReadFrequently: true })!;

  if (feather > 0) {
    mbCtx.filter = `blur(${feather}px)`;
  }
  mbCtx.drawImage(mask.canvas, 0, 0);

  const imgData = mbCtx.getImageData(0, 0, width, height);
  const d = imgData.data;
  const len = d.length;

  for (let i = 0; i < len; i += 4) {
    const a = d[i + 3];
    if (a === 0) {
      d[i + 3] = Math.round((1 - density) * 255);
      continue;
    }
    const r = d[i];
    const g = d[i + 1];
    const b = d[i + 2];
    const lum = (r * 77 + g * 150 + b * 29) >> 8;
    const reveal = (lum * a) / 65025;
    const effectiveAlpha = 1 - density * (1 - reveal);
    d[i + 3] = Math.round(effectiveAlpha * 255);
  }

  mbCtx.filter = 'none';
  mbCtx.putImageData(imgData, 0, 0);

  targetCtx.save();
  targetCtx.globalCompositeOperation = 'destination-in';
  targetCtx.drawImage(mBuf, 0, 0);
  targetCtx.restore();
}

