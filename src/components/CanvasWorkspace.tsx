            activeLayer.smartFiltersEnabled = true;
            activeLayer.smartFiltersExpanded = true;
            renderSmartLayerCanvas(activeLayer, canvasWidth, canvasHeight);
            onUpdateLayers([...layers]);
            compositeLayers();
            onClearEditingSmartFilter?.();
