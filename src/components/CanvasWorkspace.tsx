  const handleCancelAdjustment = () => {
    try {
      const backup = adjustmentBackupCanvasRef.current;
      const activeLayer = layers.find((l) => l.id === activeLayerId);
      if (activeLayer) {
        if (activeLayer.type === 'smart') {
          renderSmartLayerCanvas(activeLayer, canvasWidth, canvasHeight);
        } else if (backup) {
          activeLayer.ctx.clearRect(0, 0, canvasWidth, canvasHeight);
          activeLayer.ctx.drawImage(backup, 0, 0);
        }
      }
      compositeLayers();
    } finally {
      lastAdjustmentParamsRef.current = null;
      adjustmentBackupCanvasRef.current = null;
      onCloseAdjustment();
      onClearEditingSmartFilter?.();
    }
  };

