        if (transformState.isActive) {
          e.preventDefault();
          handleCancelTransform();
          return;
        }
        if (activeAdjustment) {
          e.preventDefault();
          handleCancelAdjustment();
          return;
        }
        if (activeTool === 'select' || selectionState.isActive) {
          e.preventDefault();
          handleDeselect();
          if (activeTool === 'select' && onChangeTool) onChangeTool('brush');
          return;
        }
