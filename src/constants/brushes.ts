const FOLDERS_STORAGE_KEY = 'hunbatz_base_folders_v15';

export function loadBrushFolders(): string[] {
  try {
    const saved = localStorage.getItem(FOLDERS_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        const clean = parsed.filter(
          (f: string) =>
            f &&
            !f.toLowerCase().includes('velvetcat') &&
            !f.toLowerCase().includes('custom') &&
            f !== 'Hunbatz Base Brushes' &&
            f !== 'Placeholder'
        );
        if (clean.length > 0) return clean;
      }
    }
  } catch {}
  return ['Inking'];
}

export function saveBrushFolders(folders: string[]): void {
  try {
    const clean = folders.filter(
      (f: string) =>
        f &&
        !f.toLowerCase().includes('velvetcat') &&
        !f.toLowerCase().includes('custom') &&
        f !== 'Hunbatz Base Brushes' &&
        f !== 'Placeholder'
    );
    localStorage.setItem(FOLDERS_STORAGE_KEY, JSON.stringify(clean));
  } catch {}
}