export function hydrateBrush(b: any): Brush {
  const rawRoundness =
    b.shape?.roundness ?? b.roundness ?? 1.0;
  const normRoundness =
    rawRoundness > 1.05
      ? Math.max(0.05, Math.min(1, rawRoundness / 100))
      : Math.max(0.05, Math.min(1, Number(rawRoundness) || 1.0));

  const rawAngle =
    b.shape?.rotation ?? b.shape?.angle ?? b.angle ?? 0;

  const spacing = b.strokePath?.spacing ?? b.spacing ?? 0.05;
  const streamline = b.stabilization?.streamline ?? b.streamline ?? 0.2;
  const hardness = b.taper?.tipSharpness ?? b.hardness ?? 0.9;
  
  let texture: BrushTexture = 'hard_round';
  const rawTex = b.shape?.texture ?? b.texture;
  if (rawTex === 'pencil_grain' || rawTex === 'rough_paper') texture = 'pencil_grain';
  else if (rawTex === 'soft_airbrush' || rawTex === 'cloud_texture') texture = 'soft_airbrush';
  else if (rawTex === 'smooth_ink') texture = 'smooth_ink';
  else if (rawTex === 'bleed_ink' || rawTex === 'ink_bleed') texture = 'bleed_ink';
  else if (rawTex === 'oil_impasto' || rawTex === 'impasto') texture = 'oil_impasto';
  else if (rawTex === 'oil_bristle' || rawTex === 'rake_comb') texture = 'oil_bristle';
  else if (rawTex === 'flat_bristle') texture = 'flat_bristle';
  else if (rawTex === 'watercolor_wash') texture = 'watercolor_wash';
  else if (rawTex === 'charcoal_rough' || rawTex === 'chalk_dust') texture = 'charcoal_rough';
  else if (rawTex === 'charcoal_coarse') texture = 'charcoal_coarse';
  else if (rawTex === 'chisel_marker') texture = 'chisel_marker';
  else if (rawTex) texture = rawTex as BrushTexture;

  const hydrated: Brush = {
    id: b.id,
    name: b.name,
    category:
      b.category &&
      !b.category.toLowerCase().includes('velvetcat') &&
      !b.category.toLowerCase().includes('custom') &&
      b.category !== 'Placeholder' &&
      b.category !== 'Hunbatz Base Brushes'
        ? b.category
        : 'Inking',
    description: b.description || 'Studio Brush Preset',
    size: b.size ?? 24,
    opacity: b.opacity ?? 1.0,
    hardness,
    streamline,
    spacing,
    jitter: b.strokePath?.jitter ?? b.jitter ?? 0,
    texture,
    pressureSizeFactor: b.pressureSizeFactor ?? 0.8,
    pressureOpacityFactor: b.pressureOpacityFactor ?? 0.0,
    minSize: b.minSize ?? 1,
    maxSize: b.maxSize ?? 400,
    author: b.author || 'Hunbatz Studio',
    isCustom: b.isCustom ?? false,
    strokePath: {
      spacing,
      streamline,
      jitter: b.strokePath?.jitter ?? b.jitter ?? 0,
      fallOff: b.strokePath?.fallOff ?? 0,
    },
    stabilization: {
      streamline,
      stabilization: b.stabilization?.stabilization ?? 0.2,
      motionFiltering: b.stabilization?.motionFiltering ?? 0,
    },
    taper: {
      pressureTaper: b.taper?.pressureTaper ?? 0,
      tipSharpness: hardness,
      sizeTaper: b.taper?.sizeTaper ?? 0,
      opacityTaper: b.taper?.opacityTaper ?? 0,
    },
    shape: {
      texture,
      scatter: b.shape?.scatter ?? 0,
      rotation: ((Number(rawAngle) || 0) % 360 + 360) % 360,
      followStroke: b.shape?.followStroke ?? false,
      count: b.shape?.count ?? 1,
      countJitter: b.shape?.countJitter ?? 0,
      roundness: normRoundness,
      ...(b.shape || {}),
    },
    grain: {
      texture: (b.grain?.texture && b.grain.texture !== 'none' ? b.grain.texture : 'blank') as any,
      mode: b.grain?.mode || 'moving',
      scale: b.grain?.scale ?? 1,
      depth: b.grain?.depth ?? 0,
      contrast: b.grain?.contrast ?? 1.0,
    },
    rendering: {
      mode: b.rendering?.mode ?? 'heavy_glaze',
      wetEdges: b.rendering?.wetEdges ?? 0,
      flow: b.rendering?.flow ?? 1.0,
      blendMode: b.rendering?.blendMode ?? 'source-over',
    },
    wetMix: {
      dilution: b.wetMix?.dilution ?? 0,
      charge: b.wetMix?.charge ?? 1.0,
      attack: b.wetMix?.attack ?? 0.8,
      pull: b.wetMix?.pull ?? 0,
    },
    colorDynamics: {
      stampHueJitter: b.colorDynamics?.stampHueJitter ?? 0,
      stampSatJitter: b.colorDynamics?.stampSatJitter ?? 0,
      stampLightJitter: b.colorDynamics?.stampLightJitter ?? 0,
      strokeHueJitter: b.colorDynamics?.strokeHueJitter ?? 0,
      pressureHueShift: b.colorDynamics?.pressureHueShift ?? 0,
    },
    dynamics: {
      speedSize: b.dynamics?.speedSize ?? 0,
      speedOpacity: b.dynamics?.speedOpacity ?? 0,
      jitterSize: b.dynamics?.jitterSize ?? 0,
      jitterOpacity: b.dynamics?.jitterOpacity ?? 0,
    },
    penControls: {
      pressureSizeCurve: b.penControls?.pressureSizeCurve ?? 1,
      pressureOpacityCurve: b.penControls?.pressureOpacityCurve ?? 1,
      tiltAngle: b.penControls?.tiltAngle ?? true,
      tiltOpacity: b.penControls?.tiltOpacity ?? 0,
      tiltGradation: b.penControls?.tiltGradation ?? 0,
      tiltSize: b.penControls?.tiltSize ?? 0,
    },
    properties: {
      orientToScreen: b.properties?.orientToScreen ?? true,
      useStampPreview: b.properties?.useStampPreview ?? true,
      minSize: b.minSize ?? 1,
      maxSize: b.maxSize ?? 400,
    },
    materials: {
      metallic: b.materials?.metallic ?? 0,
      roughness: b.materials?.roughness ?? 0.5,
    },
    applePencil: {
      pressureSize: b.applePencil?.pressureSize ?? 0.8,
      pressureOpacity: b.applePencil?.pressureOpacity ?? 0,
      pressureFlow: b.applePencil?.pressureFlow ?? 0,
      pressureBleed: b.applePencil?.pressureBleed ?? 0,
      pressureSoftness: b.applePencil?.pressureSoftness ?? 0,
      tiltAngle: b.applePencil?.tiltAngle ?? 0,
      tiltOpacity: b.applePencil?.tiltOpacity ?? 0,
      tiltGradation: b.applePencil?.tiltGradation ?? 0,
      tiltBleed: b.applePencil?.tiltBleed ?? 0,
      tiltSize: b.applePencil?.tiltSize ?? 0,
    },
    smudge: {
      strength: b.smudge?.strength ?? 0.5,
      jitter: b.smudge?.jitter ?? 0,
      brushFlow: b.smudge?.brushFlow ?? 0.5,
    },
  };

  const extraKeys = [
    'shapeTextureUrl',
    'grainTextureUrl',
    'iconUrl',
    'engine',
    'kritaEngine',
    'kritaPatternId',
    'patternEnabled',
    'patternStrength',
    'patternScale',
    'patternTexturingMode',
    'patternCutoff',
    'patternInvert',
    'patternContrast',
    'patternBrightness',
    'patternOffsetX',
    'patternOffsetY',
    'patternStrengthPressure',
    'spikes',
    'density',
    'randomness',
    'darkenAmount',
    'sizeByPressure',
    'opacityByPressure',
    'sensors',
    'shareCurveAcrossSettings',
    'blendMode',
  ];
  for (const k of extraKeys) {
    if ((b as any)[k] !== undefined) {
      (hydrated as any)[k] = (b as any)[k];
    }
  }

  return hydrated;
}

